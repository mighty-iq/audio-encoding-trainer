#!/usr/bin/env python3
"""Build tests/fixtures/audio-fixture.js: synthetic clips (no recordings) as base64 MP3, 16 kHz mono, 24 kbps,
the same format as the real packs. Speech-like clips: a harmonic source with a moving F0, three formant resonances
that change per syllable, syllable envelopes, short pauses and a few fricative bursts. Run:
    python3 tests/e2e/audio_fixture_build.py
Needs numpy, scipy and ffmpeg with libmp3lame. Deterministic (fixed seeds). MIT licence."""
import base64
import json
import os
import subprocess
import sys
import tempfile

import numpy as np
from scipy.signal import lfilter, butter

SR = 16000
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'fixtures', 'audio-fixture.js')
VOWELS = [(730, 1090, 2440), (270, 2290, 3010), (530, 1840, 2480), (570, 840, 2410), (440, 1020, 2240), (300, 870, 2240)]


def resonator(x, f, bw):
    r = np.exp(-np.pi * bw / SR)
    a = [1, -2 * r * np.cos(2 * np.pi * f / SR), r * r]
    b = [1 - r]
    return lfilter(b, a, x)


def speechlike(dur, f0, seed, rate=4.0):
    rng = np.random.default_rng(seed)
    n = int(dur * SR)
    t = np.arange(n) / SR
    f0t = f0 * (1 + 0.06 * np.sin(2 * np.pi * 0.7 * t + rng.uniform(0, 6))) * (1 - 0.08 * t / dur)
    ph = 2 * np.pi * np.cumsum(f0t) / SR
    src = np.zeros(n)
    for k in range(1, int(4000 / f0) + 1):
        src += np.sin(k * ph) / k
    out = np.zeros(n)
    pos = 0.06
    while pos < dur - 0.12:
        L = rng.uniform(0.7, 1.3) / rate
        if pos + L > dur - 0.06:
            break
        a, b = int(pos * SR), int((pos + L) * SR)
        f1, f2, f3 = VOWELS[rng.integers(len(VOWELS))]
        seg = src[a:b]
        y = resonator(seg, f1, 80) * 1.0 + resonator(seg, f2, 100) * 0.6 + resonator(seg, f3, 140) * 0.3
        env = np.sin(np.pi * np.linspace(0, 1, b - a)) ** 0.7 * rng.uniform(0.5, 1.0)
        out[a:b] += y * env
        if rng.random() < 0.35:  # fricative burst at the onset
            m = int(rng.uniform(0.03, 0.07) * SR)
            bb, aa = butter(2, [3000 / (SR / 2), 7000 / (SR / 2)], btype='band')
            nz = lfilter(bb, aa, rng.standard_normal(m)) * np.hanning(m) * 0.25
            out[a:a + m] += nz
        pos += L + (rng.uniform(0.12, 0.3) if rng.random() < 0.2 else rng.uniform(0.0, 0.03))
    out /= np.sqrt(np.mean(out ** 2)) + 1e-12
    return out * 10 ** (-24 / 20)


def ambience(dur, seed):
    rng = np.random.default_rng(seed)
    n = int(dur * SR)
    w = rng.standard_normal(n)
    # pink-ish noise via a 3-pole filter, slow level drift, a few soft clatters
    b = [0.049922035, -0.095993537, 0.050612699, -0.004408786]
    a = [1, -2.494956002, 2.017265875, -0.522189400]
    x = lfilter(b, a, w)
    x *= 1 + 0.25 * np.sin(2 * np.pi * 0.21 * np.arange(n) / SR)
    for _ in range(int(dur * 1.5)):
        p = rng.integers(0, n - 800)
        x[p:p + 800] += rng.standard_normal(800) * np.exp(-np.arange(800) / 120) * 3
    x /= np.sqrt(np.mean(x ** 2))
    return x * 10 ** (-26 / 20)


def tone(dur, f, db):
    t = np.arange(int(dur * SR)) / SR
    y = np.sin(2 * np.pi * f * t) * np.sqrt(2) * 10 ** (db / 20)
    r = int(0.01 * SR)
    y[:r] *= np.linspace(0, 1, r)
    y[-r:] *= np.linspace(1, 0, r)
    return y


def mp3(y):
    with tempfile.TemporaryDirectory() as d:
        wav, out = os.path.join(d, 'a.f32'), os.path.join(d, 'a.mp3')
        np.clip(y, -1, 1).astype('<f4').tofile(wav)
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'f32le', '-ar', str(SR), '-ac', '1', '-i', wav,
                        '-c:a', 'libmp3lame', '-b:a', '24k', '-ar', str(SR), '-ac', '1', '-map_metadata', '-1',
                        '-write_xing', '1', out], check=True)
        with open(out, 'rb') as f:
            return f.read()


def main():
    clips = {}
    talkers = {'a': 120, 'b': 210, 'c': 150, 'd': 100, 'e': 185}
    for i, (v, f0) in enumerate(talkers.items()):
        clips['fx.%s.phrase.one' % v] = ('phrase', speechlike(1.8 + 0.15 * i, f0, 100 + i))
        clips['fx.%s.phrase.two' % v] = ('phrase', speechlike(1.4 + 0.1 * i, f0 * 1.03, 200 + i))
    for i in range(6):
        clips['fx.bab%d.sentence.long' % i] = ('sentence', speechlike(3.0 + 0.2 * i, 95 + 25 * i, 300 + i, rate=4.5))
    clips['fx.bed.cafe'] = ('bed', ambience(6.0, 400))
    clips['fx.tone.1k'] = ('number', tone(1.0, 1000, -20))
    meta, packs = {}, {}
    for cid, (kind, y) in clips.items():
        data = mp3(y)
        packs[cid] = base64.b64encode(data).decode('ascii')
        meta[cid] = {'pack': 'fixture', 'voice': cid.split('.')[1], 'kind': kind, 'text': cid.split('.')[-1],
                     'words': [], 'dur': round(len(y) / SR, 3), 'set': 'train', 'asr': {'ok': True}}
    js = ('/* Generated by tests/e2e/audio_fixture_build.py: synthetic speech-like clips, tones and noise (no '
          'recordings), MP3 16 kHz mono 24 kbps. Test fixture only; never shipped. MIT licence. */\n'
          '(function (root) {\n  var ES = root.ES = root.ES || {};\n  ES.data = ES.data || {}; ES.packs = ES.packs || {};\n'
          '  ES.data.manifest = ES.data.manifest || { version: "fixture", clips: {} };\n'
          '  var meta = ' + json.dumps(meta, separators=(',', ':')) + ';\n'
          '  for (var k in meta) ES.data.manifest.clips[k] = meta[k];\n'
          '  ES.packs.fixture = ' + json.dumps(packs, separators=(',', ':')) + ';\n'
          '})(typeof window !== "undefined" ? window : globalThis);\n')
    with open(OUT, 'w') as f:
        f.write(js)
    print('wrote', os.path.relpath(OUT), len(js) // 1024, 'KB,', len(clips), 'clips')


if __name__ == '__main__':
    sys.exit(main())
