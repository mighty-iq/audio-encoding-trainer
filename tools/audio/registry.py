def f0_median(x, sr=SR, fmin=65, fmax=400):
    """Median F0 (Hz) of voiced 40 ms frames by normalised autocorrelation (frames with r > 0.6)."""
    n, hop = int(0.04 * sr), int(0.01 * sr)
    lo, hi = int(sr / fmax), int(sr / fmin)
    vals = []
    for s in range(0, len(x) - n - hi, hop):
        f = x[s:s + n + hi].astype(np.float64)
        a = f[:n] - f[:n].mean()
        e0 = float(np.dot(a, a))
        if e0 < 1e-6:
            continue
        best, lag = 0.0, 0
        for k in range(lo, hi):
            b = f[k:k + n] - f[k:k + n].mean()
            r = float(np.dot(a, b)) / math.sqrt(e0 * float(np.dot(b, b)) + 1e-12)
            if r > best:
                best, lag = r, k
        if best > 0.6 and lag:
            vals.append(sr / lag)
    return round(float(np.median(vals)), 1) if vals else None


def voice_meta():
    """Static metadata per voice id '<src>.<voice>' from the plan and the natural-source tables."""
    meta = {}
    for v, sex, acc in P.KOKORO_EN:
        meta[f'kokoro.{v}'] = {'sex': sex, 'accent': f'{acc} English (synthetic)'}
    for v, sex, acc in P.KOKORO_ACCENT:
        meta[f'kokoro.{v}'] = {'sex': sex, 'accent': f'English with a {acc} accent (synthetic)'}
    for v, d in getattr(P, 'PIPER_VOICES', {}).items():
        meta[f'piper-libritts.{v}'] = {'sex': d['sex'], 'accent': 'North American English (synthetic)'}
    for v, d in getattr(P, 'NATURAL_VOICES', {}).items():
        meta[v] = dict(d)
    for v in LIC_VOICE:
        meta[v] = {'sex': 'u', 'accent': '', 'noise': True}
    return meta


def build_voices(man, log):
    meta = voice_meta()
    by_voice = {}
    for cid, e in man['clips'].items():
        by_voice.setdefault(e['voice'], []).append((cid, e))
    cast = {k: {'name': v['name'], 'venue': v['venue'], 'blurb': v['blurb']} for k, v in P.cast().items()}
    tf = REPO / 'tools' / 'audio' / 'voice_tiers.json'
    tiers = json.load(open(tf)) if tf.exists() else {}
    out = {}
    for vid in sorted(by_voice):
        clips = by_voice[vid]
        src = vid.split('.', 1)[0]
        sets = {e['set'] for _, e in clips}
        if len(sets) > 1:
            raise SystemExit(f'voice {vid} has clips in both sets: {sets}')
        m = meta.get(vid, {})
        speech = [c for c, e in clips if e['kind'] in ('word', 'name', 'number', 'phrase', 'sentence', 'intro')]
        sample = np.concatenate([load_audio(wav_path(c)) for c in speech[:8]]) if speech else None
        f0 = f0_median(sample) if sample is not None else None
        v = {'src': src, 'sex': m.get('sex', 'u'), 'accent': m.get('accent', ''), 'set': sets.pop(),
             'licence': LIC_VOICE.get(vid, LIC.get(src, '')), 'f0': f0, 'clips': len(clips)}
        if m.get('noise'):
            v['noise'] = True
        if m.get('ageBand'):
            v['ageBand'] = m['ageBand']
        if vid in cast:
            v['cast'] = cast[vid]
        if vid in tiers:
            v['tier'] = tiers[vid]['tier']
        out[vid] = v
    write_js(STAGE / 'data' / 'voices.js', 'window.ES = window.ES || {}; ES.data = ES.data || {}; ES.data.voices', out)
    log(f'voices: {len(out)} ({sum(1 for v in out.values() if v["set"] == "probe")} probe)')
    return out


def neighbours_for(word, pool, family):
    fam = [w for w in family if w != word]
    near = [w for w in lexicon.neighbours(word, pool, 1) if w not in fam]
    far = [w for w in lexicon.neighbours(word, pool, 2) if w not in fam and w not in near]
    return (fam + near + far)[:8]


def closest(word, pool, n):
    """Up to n words of the same closed set ordered by phonetic distance (text-only foils)."""
    d = sorted((lexicon.phon_distance(word, w), w) for w in pool if w != word)
    return [w for _, w in d[:n]]


def with_audio(items, texts):
    """Only items that have at least one clip (matched by normalised text), so the app never picks an item
    it cannot play; the engine's adapter falls back (e.g. Far to call-sign phrases) while a list is empty."""
    from common import norm_words
    return [it for it in items if ' '.join(norm_words(it['text'])) in texts]


def sound_alikes(word, pool):
    def stressed(w):
        p = lexicon.prons(w, stress=True)
        return next((ph[:-1] for ph in p[0] if ph.endswith('1')), None) if p else None
    return [w for w in pool if w != word and lexicon.phon_distance(word, w) <= 2 and stressed(w) == stressed(word)]


def build_vocab(log, man=None):
    import content_cast  # noqa: F401  (cast text comes from the plan)
    from common import norm_words
    texts = {' '.join(norm_words(e['text'])) for e in (man or {}).get('clips', {}).values()
             if e['kind'] in ('phrase', 'sentence', 'story', 'intro')}
    import content_echo as CE
    import content_phrases as CF
    import content_probe as CP
    import content_repair as CR
    import content_sus as CS
    fam_of = {w: f for f, ws in cw.RHYMES.items() for w in ws}
    nb = {w: neighbours_for(w, cw.NOUNS, cw.RHYMES[fam_of[w]]) for w in cw.NOUNS}
    # numbers one-nine have no true sound-alikes among themselves, so they carry no neighbour list; names keep
    # only real near-rhymes (same stressed vowel and at most two phonemes apart, e.g. harper/parker)
    nb.update({n: [] for n in cw.NUMBERS})
    nb.update({n: sound_alikes(n, cw.NAMES) for n in cw.NAMES})
    voc = {'names': cw.NAMES, 'numbers': cw.NUMBERS, 'nouns': cw.NOUNS, 'rhymes': cw.RHYMES, 'family': fam_of,
           'neighbours': nb,
           'sus': with_audio(CS.items(), texts), 'susPools': CS.pools(),
           'phrases': with_audio(CF.items(), texts),
           'repair': with_audio(CR.sentences(), texts),
           'echo': with_audio(CE.items(), texts), 'echoValues': CE.values(),
           'intros': {e['voice']: e['text'] for e in sorted((man or {}).get('clips', {}).values(),
                                                              key=lambda e: e['text']) if e['kind'] == 'intro'},
           'stories': with_audio(CP.vocab('stories'), texts), 'matrix': CP.vocab('matrix'),
           'twovoices': with_audio(CP.vocab('twovoices'), texts)}
    write_js(STAGE / 'data' / 'vocab.js', 'window.ES = window.ES || {}; ES.data = ES.data || {}; ES.data.vocab', voc)
    log(f"vocab: {len(voc['nouns'])} nouns, {len(voc['sus'])} sus, {len(voc['phrases'])} phrases, "
        f"{len(voc['repair'])} repair, {len(voc['echo'])} echo, {len(voc['stories'])} stories")
    return voc


def build_ltas(man, log, nfft=512):
    """Long-term average spectrum of the training speech (power over active frames), for speech-shaped
    noise. 'mag' = dB per FFT bin (nfft 512 at 16 kHz, 0 dB = max); 'third' = 1/3-octave band levels."""
    win = np.hanning(nfft)
    acc = np.zeros(nfft // 2 + 1)
    frames = 0
    ids = [c for c, e in man['clips'].items() if e['set'] == 'train'
           and e['kind'] in ('word', 'name', 'number', 'phrase', 'sentence')]
    for cid in ids[::max(1, len(ids) // 600)]:
        x = load_audio(wav_path(cid))
        e = man['clips'][cid]
        x = x * (10 ** ((-20 - e['adb']) / 20))       # every clip at the same active level
        for s in range(0, len(x) - nfft, nfft // 2):
            f = x[s:s + nfft]
            if 20 * math.log10(np.sqrt(np.mean(f * f)) + 1e-9) < -50:
                continue
            acc += np.abs(np.fft.rfft(f * win)) ** 2
            frames += 1
    p = acc / max(frames, 1)
    mag = 10 * np.log10(p / p.max() + 1e-12)
    freqs = np.fft.rfftfreq(nfft, 1 / SR)
    fc = [100 * 2 ** (i / 3) for i in range(0, 20)]
    third = []
    for f in fc:
        band = (freqs >= f / 2 ** (1 / 6)) & (freqs < f * 2 ** (1 / 6))
        third.append(round(float(10 * np.log10(p[band].mean() / p.max() + 1e-12)), 2) if band.any() else None)
    out = {'sr': SR, 'nfft': nfft, 'mag': [round(float(v), 2) for v in mag], 'frames': frames,
           'third': {'fc': [round(f, 1) for f in fc], 'db': third}}
    write_js(STAGE / 'data' / 'ltas.js', 'window.ES = window.ES || {}; ES.data = ES.data || {}; ES.data.ltas', out)
    log(f'ltas: {frames} frames from {len(ids)} training clips')
    return out


