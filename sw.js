/** Run fn over items, n at a time; rejects at the first failure. */
function pool(items, n, fn) {
  return new Promise(function (resolve, reject) {
    var next = 0, running = 0, failed = false;
    function pump() {
      if (failed) return;
      if (next >= items.length && running === 0) { resolve(); return; }
      while (running < n && next < items.length) {
        running++;
        fn(items[next++]).then(function () { running--; pump(); }, function (e) { failed = true; reject(e); });
      }
    }
    pump();
  });
}
