/* ES.game.cast — the cast gallery's logic (pure; loads in Node). The cast is every training voice that carries a
   `cast` field in data/voices.js ({name, venue, blurb}, generated by tools/audio). A card fills in as the player
   meets the voice (hears it as the voice to follow in any exercise, or meets it in Voices) and as the player
   identifies it ("Who is talking?" answered right in Voices). Known = identified KNOWN_AT times or more.
   Synthetic voices are labelled synthetic (PLAN §15). Trial notes are buffered between sets and written by
   record.js at the set's end (never during a stimulus). Record: game.cast[voiceId] = {met, n, id, at}. */
(function (root) {
  'use strict';
  var ES = root.ES = root.ES || {};
  ES.game = ES.game || {};
  var KNOWN_AT = 3, SYNTH = { kokoro: 1, 'piper-libritts': 1, piper: 1 };
  var buf = {};

  function voices() { return (ES.data && ES.data.voices) || {}; }
  function K() { return ES.game.core; }
  function venueOrder(id) { var v = ES.game.data && ES.game.data.venue(id); return v ? v.order : 99; }

  /** Cast members: [{id, name, venue, blurb, sex, accent, synthetic, f0, src}] in venue order, then by name. */
  function list() {
    var V = voices(), out = [];
    Object.keys(V).forEach(function (id) {
      var vo = V[id];
      if (!vo || !vo.cast || !vo.cast.name || vo.set === 'probe') return;
      out.push({ id: id, name: String(vo.cast.name), venue: vo.cast.venue || null, blurb: vo.cast.blurb || '', sex: vo.sex || '',
        accent: String(vo.accent || '').replace(/\s*\(synthetic\)\s*/i, '').trim(), synthetic: !!SYNTH[vo.src], f0: typeof vo.f0 === 'number' ? vo.f0 : null,
        src: vo.src || '' });
    });
    out.sort(function (a, b) { return venueOrder(a.venue) - venueOrder(b.venue) || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0); });
    return out;
  }
  function isCast(id) { var vo = voices()[id]; return !!(vo && vo.cast && vo.cast.name && vo.set !== 'probe'); }

  /** Merged progress for a voice: stored record + this set's buffer + the engine's Voices count (imports). */
  function progress(id, rec) {
    rec = rec || K().rec();
    var r = (rec.cast || {})[id] || {}, b = buf[id] || {};
    var L = ES.engine && ES.engine.learner, lc = L && L.state && L.state.cast ? (L.state.cast[id] || 0) : 0;
    var met = r.met || b.met || (lc > 0 ? (r.at || 1) : 0);
    return { met: met || 0, n: Math.max((r.n || 0) + (b.n || 0), lc), id: (r.id || 0) + (b.id || 0), at: Math.max(r.at || 0, b.at || 0) };
  }
  function stateOf(p) { return !p.met ? 'unmet' : p.id >= KNOWN_AT ? 'known' : 'met'; }
  function cards(rec) {
    rec = rec || K().rec();
    return list().map(function (c) {
      var p = progress(c.id, rec), out = {};
      Object.keys(c).forEach(function (k) { out[k] = c[k]; });
      out.state = stateOf(p); out.met = p.met; out.heard = p.n; out.identified = p.id; out.at = p.at;
      return out;
    });
  }
  function card(id, rec) { return cards(rec).filter(function (c) { return c.id === id; })[0] || null; }
  function counts(rec) {
    var cs = cards(rec), c = { total: cs.length, met: 0, known: 0 };
    cs.forEach(function (x) { if (x.state !== 'unmet') c.met++; if (x.state === 'known') c.known++; });
    return c;
  }

  /** Note one answered trial. Returns {met:[ids newly met], known:[ids newly known]} for this trial. */
  function noteTrial(trial, result, at) {
    var out = { met: [], known: [] };
    if (!trial || !trial.meta || trial.meta.demo || trial.meta.probe) return out;
    var m = trial.meta, vs = m.voices || [], t = m.newVoice || vs[0];
    at = at || K().now();
    if (t && isCast(t)) {
      var before = progress(t), b = buf[t] = buf[t] || { met: 0, n: 0, id: 0, at: 0 };
      if (!before.met) { b.met = at; out.met.push(t); }
      b.n++; b.at = at;
      if (trial.ex === 'voices' && m.task === 'who' && result && result.correct) {
        b.id++;
        if (before.id + 0 < KNOWN_AT && before.id + 1 >= KNOWN_AT) out.known.push(t);
      }
    }
    return out;
  }
  /** Mark a voice as met outside a trial (custom views: the hook `cast:met` {voice}). */
  function noteMet(id, at) {
    if (!isCast(id)) return false;
    var b = buf[id] = buf[id] || { met: 0, n: 0, id: 0, at: 0 };
    if (!progress(id).met) b.met = at || K().now();
    return true;
  }
  /** Move the buffer into the record r (inside store.update). Returns the ids written. */
  function flush(r) {
    var ids = Object.keys(buf);
    r.cast = r.cast || {};
    ids.forEach(function (id) {
      var b = buf[id], c = r.cast[id] || {};
      r.cast[id] = { met: c.met || b.met || b.at, n: (c.n || 0) + b.n, id: (c.id || 0) + b.id, at: Math.max(c.at || 0, b.at || 0) };
    });
    buf = {};
    return ids;
  }
  function pending() { return Object.keys(buf).length; }
  /** Counts from the stored record alone (no buffer): {met, known}. */
  function storedCounts(rec) {
    var c = { met: 0, known: 0 }, rc = (rec && rec.cast) || {};
    list().forEach(function (x) { var r = rc[x.id]; if (r && r.met) { c.met++; if ((r.id || 0) >= KNOWN_AT) c.known++; } });
    return c;
  }
  /** "about 195 Hz" (median voice pitch from the stimulus pipeline). */
  function pitchText(f0) { return typeof f0 === 'number' && f0 > 0 ? 'about ' + Math.round(f0 / 5) * 5 + ' Hz' : ''; }

  ES.game.cast = { KNOWN_AT: KNOWN_AT, list: list, isCast: isCast, cards: cards, card: card, counts: counts, progress: progress,
    noteTrial: noteTrial, noteMet: noteMet, flush: flush, pending: pending, storedCounts: storedCounts, pitchText: pitchText,
    _reset: function () { buf = {}; } };
})(typeof window !== 'undefined' ? window : globalThis);
