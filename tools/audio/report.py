"""Write the numbers section of docs/dev/STIMULI.md (between the stats markers) from the render databases,
the logs and the last pack/validate run. Usage: python3 -I tools/audio/report.py"""
import collections
import json
import re
import sys

sys.path.insert(0, __import__('os').path.dirname(__file__))
import jobs as J  # noqa: E402
from common import REPO, WORK, Results, utc_now  # noqa: E402

START, END = '<!-- stats:start -->', '<!-- stats:end -->'


def job_stats():
    sent = Results('sentences')
    rows = []
    for name, fn in J.JOBS.items():
        items = fn()
        if not items:
            continue
        kept = first = alt = 0
        for it in items:
            ids = [it['id']] + [a['id'] for a in it.get('alts', [])]
            hit = next((i for i in ids if sent.get(i, {}).get('ok')), None)
            if hit:
                kept += 1
                r = sent.get(hit)
                if hit == it['id'] and abs(r.get('rate', 1) - it.get('speed', 1.0)) < 1e-6:
                    first += 1
                elif hit != it['id']:
                    alt += 1
        log = WORK / 'logs' / f'phrases-{name}.log'
        misses = sum(1 for line in log.read_text().splitlines() if ' miss ' in line) if log.exists() else 0
        rows.append((name, len(items), kept, first, alt, misses))
    return rows


def main():
    summ = json.load(open(WORK / 'pack-summary.json'))
    val = json.load(open(WORK / 'validate.json'))
    rej = json.load(open(WORK / 'pack_rejects.json')) if (WORK / 'pack_rejects.json').exists() else []
    man = json.load(open(WORK / 'manifest.json'))['clips']
    out = [START, f'_Generated by tools/audio/report.py at {utc_now()}._', '',
           f"Total: {val['clips']} clips, {val['voices']} voices, {val['mp3_bytes'] / 1e6:.2f} MB of MP3 "
           f"(budget 8.5 MB); recogniser pass on the decoded MP3 of kept speech clips: {val['asr_pass']:.1%}; "
           f"clips sent back after MP3 coding in the last pack: {len(rej)}.", '',
           '| Pack | Clips | Seconds | MP3 MB | JS MB | Exercises |', '|---|---|---|---|---|---|']
    for pk, d in sorted(summ['packs'].items()):
        out.append(f"| {pk} | {d['clips']} | {d['dur']:.0f} | {d['bytes'] / 1e6:.3f} | {d['fileBytes'] / 1e6:.3f} | "
                   f"{', '.join(d['exercises'])} |")
    kinds = collections.Counter((e['kind'], e['set']) for e in man.values())
    out += ['', '| Kind | Set | Clips |', '|---|---|---|']
    out += [f'| {k} | {s} | {n} |' for (k, s), n in sorted(kinds.items())]
    srcs = collections.Counter((e['voice'].split('.')[0], e['set']) for e in man.values())
    voices = collections.defaultdict(set)
    for e in man.values():
        voices[(e['voice'].split('.')[0], e['set'])].add(e['voice'])
    out += ['', '| Source | Set | Voices | Clips |', '|---|---|---|---|']
    out += [f'| {a} | {s} | {len(voices[(a, s)])} | {n} |' for (a, s), n in sorted(srcs.items())]
    out += ['', 'Render jobs (render_phrases.py): items, kept, kept on the first render (main wording and voice at the '
            'base speed), kept with an alternative voice or wording, recogniser misses logged along the way.', '',
            '| Job | Items | Kept | First try | Alternative | Misses |', '|---|---|---|---|---|---|']
    for name, n, kept, first, alt, miss in job_stats():
        out.append(f'| {name} | {n} | {kept} | {first} ({first / max(1, n):.0%}) | {alt} | {miss} |')
    for db in ('natural', 'words'):
        if (WORK / 'db' / f'{db}.jsonl').exists():
            rs = Results(db).values()
            ok = sum(1 for r in rs if r.get('ok'))
            notes = collections.Counter(r.get('note', r.get('why', 'not recognised')) for r in rs if not r.get('ok'))
            out.append(f'\n{db}: {ok} kept of {len(rs)} rows; not kept: {dict(notes) or "none"}.')
    dropped = [r['id'] for r in Results('sentences').values() if not r.get('ok')]
    out += ['', f'Variants that failed and were replaced or dropped (sentences db): {len(dropped)}; the logs in '
            '../stimwork/logs list each miss with what the recogniser heard.', END]
    p = REPO / 'docs' / 'dev' / 'STIMULI.md'
    t = p.read_text()
    block = '\n'.join(out)
    if START in t:
        t = re.sub(re.escape(START) + '.*?' + re.escape(END), lambda m: block, t, flags=re.S)
    else:
        t = t.rstrip() + '\n\n## Numbers (last build)\n' + block + '\n'
    p.write_text(t)
    print('report written')


if __name__ == '__main__':
    main()
