#!/usr/bin/env node
// Earshot — regenerates js/ui/licence-texts.js: the notices that must travel with every copy of the app (RV-claims
// C02), shown in About → Credits so they work offline, from disk and in sandboxed previews:
//   - the SIL Open Font License 1.1 with each embedded font's copyright line (fonts/OFL-*.txt);
//   - the AudioMNIST (MIT) and CMU Pronouncing Dictionary notices (the "## Notices" section of LICENSES-ASSETS.md).
// Usage: node tools/build-licences.mjs          write the file
//        node tools/build-licences.mjs --check  exit 1 when the file is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'js/ui/licence-texts.js');

function fonts() {
  const dir = path.join(ROOT, 'fonts');
  const files = fs.readdirSync(dir).filter((f) => /^OFL-.*\.txt$/.test(f)).sort();
  if (!files.length) throw new Error('no fonts/OFL-*.txt');
  const texts = files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n'));
  const copyrights = texts.map((t) => { const m = t.match(/^Copyright[^\n)]*\)?/); return m ? m[0].trim() : t.split('\n')[0].trim(); });
  const body = (t) => { const i = t.indexOf('This Font Software is licensed'); return (i >= 0 ? t.slice(i) : t).trim(); };
  return { copyrights, ofl: body(texts[0]) };
}
function notices() {
  const md = fs.readFileSync(path.join(ROOT, 'LICENSES-ASSETS.md'), 'utf8').replace(/\r\n/g, '\n');
  const i = md.indexOf('## Notices');
  if (i < 0) throw new Error('LICENSES-ASSETS.md has no "## Notices" section');
  const rest = md.slice(i + '## Notices'.length), end = rest.search(/\n## /);
  const paras = (end >= 0 ? rest.slice(0, end) : rest).split(/\n\s*\n/).map((p) => p.replace(/\s*\n\s*/g, ' ').trim()).filter(Boolean);
  const find = (lead) => { const p = paras.find((x) => x.startsWith(lead)); if (!p) throw new Error('notice not found: ' + lead); return p; };
  return { cmu: find('CMU Pronouncing Dictionary'), audiomnist: find('AudioMNIST') };
}
export function render() {
  const f = fonts(), n = notices();
  const data = { fontCopyrights: f.copyrights, ofl: f.ofl, cmu: n.cmu, audiomnist: n.audiomnist };
  return ['/* ES.ui.licenceTexts — notices that must travel with every copy of the app (shown in About → Credits, so they',
    '   work offline and in sandboxed previews): the SIL Open Font License 1.1 for the embedded fonts (from',
    '   fonts/OFL-*.txt), and the CMU Pronouncing Dictionary and AudioMNIST notices (from LICENSES-ASSETS.md).',
    '   Generated by tools/build-licences.mjs; do not edit by hand. */',
    '(function (ES) {',
    "  'use strict';",
    '  ES.ui.licenceTexts = ' + JSON.stringify(data, null, 2).replace(/\n/g, '\n  ') + ';',
    '})(window.ES);', ''].join('\n');
}
function main() {
  const next = render(), cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (next !== cur) { console.error('js/ui/licence-texts.js is out of date: run node tools/build-licences.mjs'); process.exit(1); }
    console.log('js/ui/licence-texts.js is up to date');
    return;
  }
  if (next !== cur) fs.writeFileSync(OUT, next);
  console.log('js/ui/licence-texts.js: ' + next.length + ' bytes' + (next !== cur ? ' (updated)' : ''));
}
if (import.meta.url === 'file://' + process.argv[1] || process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
