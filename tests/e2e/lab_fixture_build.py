#!/usr/bin/env python3
"""Build tests/fixtures/lab-audio.js: short synthetic sounds for the Lab's browser tests (no recordings): eight
"words" of 0.3-0.5 s, four "digits", four "sentences" of ~1.5 s, a 3 s "story" and a 6 s cafe-like bed, as base64
MP3 16 kHz mono 24 kbps (the format of the real packs). The sound generators are the audio owner's fixture
functions (tests/e2e/audio_fixture_build.py), imported read-only. Run: python3 tests/e2e/lab_fixture_build.py
Deterministic. Test fixture only; never shipped. MIT licence."""
import base64
import json
import os
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import audio_fixture_build as A  # noqa: E402

OUT = HERE.parent / 'fixtures' / 'lab-audio.js'


def main():
    sounds = {}
    for i in range(8):
        sounds['labfx.word.%d' % i] = ('word', A.speechlike(0.32 + 0.025 * i, [120, 210, 150, 185][i % 4], 500 + i, rate=5.0))
    for i in range(4):
        sounds['labfx.digit.%d' % i] = ('digit', A.speechlike(0.38 + 0.03 * i, [110, 200, 140, 175][i], 600 + i, rate=5.0))
    for i in range(4):
        sounds['labfx.sentence.%d' % i] = ('sentence', A.speechlike(1.4 + 0.12 * i, [190, 205, 115, 130][i], 700 + i, rate=4.5))
    sounds['labfx.story.0'] = ('story', A.speechlike(3.0, 170, 800, rate=4.0))
    sounds['labfx.bed.cafe'] = ('bed', A.ambience(6.0, 900))
    durs, packs = {}, {}
    for sid, (kind, y) in sounds.items():
        packs[sid] = base64.b64encode(A.mp3(y)).decode('ascii')
        durs[sid] = {'kind': kind, 'dur': round(len(y) / A.SR, 3)}
    js = ('/* Generated by tests/e2e/lab_fixture_build.py: synthetic speech-like sounds and a bed (no recordings) for the Lab\'s\n'
          '   browser tests, MP3 16 kHz mono 24 kbps. LAB_SOUNDS maps sound ids to {kind, dur}; lab_e2e.py aliases every probe clip\n'
          '   of tests/fixtures/lab-data.js to one of them. Test fixture only; never shipped. MIT licence. */\n'
          '(function (root) {\n  var ES = root.ES = root.ES || {};\n  ES.packs = ES.packs || {};\n'
          '  root.LAB_SOUNDS = ' + json.dumps(durs, separators=(',', ':')) + ';\n'
          '  ES.packs.labfx = ' + json.dumps(packs, separators=(',', ':')) + ';\n'
          '})(typeof window !== "undefined" ? window : globalThis);\n')
    OUT.write_text(js)
    print('wrote', os.path.relpath(OUT), len(js) // 1024, 'KB,', len(sounds), 'sounds')


if __name__ == '__main__':
    sys.exit(main())
