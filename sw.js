function hex(buf) {
  var b = new Uint8Array(buf), s = '';
  for (var i = 0; i < b.length; i++) s += (b[i] < 16 ? '0' : '') + b[i].toString(16);
  return s;
}
function typeOf(url, resp) {
  var t = resp && resp.headers.get('Content-Type');
  if (t) return t;
  var m = /\.([a-z0-9]+)$/i.exec(new URL(url).pathname);
  return (m && TYPES[m[1].toLowerCase()]) || 'application/octet-stream';
}
/** A fresh 200 response with resp's bytes when they hash to `want`, else null (resp's body is read). */
function checked(url, resp, want) {
  if (!resp || !resp.ok) return Promise.resolve(null);
  var type = typeOf(url, resp);
  return resp.arrayBuffer().then(function (buf) {
    return crypto.subtle.digest('SHA-256', buf).then(function (h) {
      return hex(h).slice(0, 16) === want ? new Response(buf, { status: 200, statusText: 'OK', headers: { 'Content-Type': type } }) : null;
    });
  });
}
