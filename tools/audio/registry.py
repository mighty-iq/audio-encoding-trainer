def credit_key(vid):
    src = vid.split('.', 1)[0]
    return vid if vid in ('ms-snsd.demand', 'ms-snsd.freesound', 'synth.earshot') else \
        ('ms-snsd.demand' if vid == 'ms-snsd.demandprobe' else src)


def build_credits(man, log):
    keys = []
    for e in man['clips'].values():
        k = credit_key(e['voice'])
        if k not in keys:
            keys.append(k)
    order = list(CREDITS)
    keys = sorted(set(keys) | {'cmudict', 'archivo', 'jetbrains'}, key=order.index)
    out = [dict(CREDITS[k], key=k) for k in keys]
    write_js(STAGE / 'data' / 'credits.js', 'window.ES = window.ES || {}; ES.data = ES.data || {}; ES.data.credits', out)
    log(f'credits: {len(out)} entries')
    return out


def main():
    log = Log('registry')
    man = read_manifest()
    build_voices(man, log)
    build_vocab(log, man)
    build_ltas(man, log)
    build_credits(man, log)


if __name__ == '__main__':
    main()
